import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendor = path.dirname(require.resolve('@expo/vector-icons/package.json'));
const fontFile = path.join(vendor, 'build/vendor/react-native-vector-icons/Fonts/Feather.ttf');
const glyphs = JSON.parse(
  readFileSync(
    path.join(vendor, 'build/vendor/react-native-vector-icons/glyphmaps/Feather.json'),
    'utf8',
  ),
);
const bytes = readFileSync(fontFile);
const font = opentype.parse(
  bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
);
const check = process.argv.includes('--check');
// The font has small stroke overshoots beyond its em square. Keep those inside
// a common canvas, rather than clipping them or resizing individual icons.
const canvas = 25;
const number = (n) => Number(n.toFixed(4)).toString();

function output(file, value) {
  const target = path.join(root, file);
  if (check) {
    if (!existsSync(target) || !readFileSync(target).equals(Buffer.from(value))) {
      throw new Error(`Stale generated icon asset: ${file}. Run pnpm build:icons.`);
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, value);
  }
}

/** PDF has cubic curves but no quadratic operator; convert the font's quadratics. */
function pdfPath(commands) {
  let x = 0;
  let y = 0;
  let startX = 0;
  let startY = 0;
  const lines = [];
  for (const c of commands) {
    if (c.type === 'M') {
      lines.push(`${number(c.x)} ${number(c.y)} m`);
      startX = c.x;
      startY = c.y;
    } else if (c.type === 'L') {
      lines.push(`${number(c.x)} ${number(c.y)} l`);
    } else if (c.type === 'C') {
      lines.push(
        `${number(c.x1)} ${number(c.y1)} ${number(c.x2)} ${number(c.y2)} ${number(c.x)} ${number(c.y)} c`,
      );
    } else if (c.type === 'Q') {
      const x1 = x + ((c.x1 - x) * 2) / 3;
      const y1 = y + ((c.y1 - y) * 2) / 3;
      const x2 = c.x + ((c.x1 - c.x) * 2) / 3;
      const y2 = c.y + ((c.y1 - c.y) * 2) / 3;
      lines.push(
        `${number(x1)} ${number(y1)} ${number(x2)} ${number(y2)} ${number(c.x)} ${number(c.y)} c`,
      );
    } else if (c.type === 'Z') {
      lines.push('h');
      x = startX;
      y = startY;
      continue;
    } else throw new Error(`Unsupported font path command: ${c.type}`);
    x = c.x;
    y = c.y;
  }
  return lines.join('\n');
}

function vectorPdf(commands) {
  const stream = `q\n1 0 0 -1 0 ${canvas} cm\n0 g\n${pdfPath(commands)}\nf\nQ\n`;
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${canvas} ${canvas}] /Resources << >> /Contents 4 0 R >>`,
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}endstream`,
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (const [index, object] of objects.entries()) {
    offsets.push(Buffer.byteLength(pdf));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  }
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 5\n0000000000 65535 f \n${offsets
    .slice(1)
    .map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`)
    .join('')}`;
  pdf += `trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return pdf;
}

const names = Object.keys(glyphs).sort();
const identifiers = new Set();
for (const name of names) {
  const identifier = `cratie_icon_${name.replaceAll('-', '_')}`;
  if (identifiers.has(identifier))
    throw new Error(`Duplicate native icon identifier: ${identifier}`);
  identifiers.add(identifier);
  const glyph = font.charToGlyph(String.fromCodePoint(glyphs[name]));
  if (glyph.index === 0) throw new Error(`Missing font glyph: ${name}`);
  const outline = glyph.getPath(0.25, (font.ascender / font.unitsPerEm) * 24 + 0.25, 24);
  const bounds = outline.getBoundingBox();
  if (bounds.x1 < 0 || bounds.y1 < 0 || bounds.x2 > canvas || bounds.y2 > canvas) {
    throw new Error(`Icon exceeds the native canvas: ${name}`);
  }
  output(
    `modules/cratie-icons/android/src/main/res/drawable/${identifier}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build-icons.mjs from Feather. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="25dp" android:height="25dp" android:viewportWidth="25" android:viewportHeight="25">\n  <path android:fillColor="#FFFFFFFF" android:pathData="${outline.toPathData(4)}" />\n</vector>\n`,
  );
  const set = `modules/cratie-icons/ios/Icons.xcassets/${identifier}.imageset`;
  output(`${set}/${identifier}.pdf`, vectorPdf(outline.commands));
  output(
    `${set}/Contents.json`,
    `${JSON.stringify(
      {
        images: [{ filename: `${identifier}.pdf`, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 },
        properties: {
          'preserves-vector-representation': true,
          'template-rendering-intent': 'template',
        },
      },
      null,
      2,
    )}\n`,
  );
}
output(
  'modules/cratie-icons/ios/Icons.xcassets/Contents.json',
  `${JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2)}\n`,
);
// IDs are looked up by name. Preserve these resources in minified releases.
output(
  'modules/cratie-icons/android/src/main/res/raw/cratie_icons_keep.xml',
  '<?xml version="1.0" encoding="utf-8"?>\n<resources xmlns:tools="http://schemas.android.com/tools" tools:keep="@drawable/cratie_icon_*" />\n',
);
output(
  'src/ui/iconNames.ts',
  `// Generated by scripts/build-icons.mjs. Do not edit.\nexport type IconName =\n${names.map((name) => `  | '${name}'`).join('\n')};\n`,
);
console.log(
  `${check ? 'Verified' : 'Generated'} ${names.length} Feather icons for Android and iOS.`,
);
